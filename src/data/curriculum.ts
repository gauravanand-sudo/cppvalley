export const youtubeIds: Partial<Record<number, string>> = {
};

const pad = (value: number) => String(value).padStart(2, "0");

const slugify = (value: string) =>
  value
    .toLowerCase()
    .replace(/c\+\+/g, "cpp")
    .replace(/[–—]/g, "-")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function phaseFor(number: number) {
  if (number <= 8) return 1;
  if (number <= 20) return 2;
  if (number <= 32) return 3;
  if (number <= 44) return 4;
  if (number <= 56) return 5;
  if (number <= 68) return 6;
  if (number <= 80) return 7;
  if (number <= 88) return 8;
  return 9;
}

function lesson(
  number: number,
  title: string,
  tracks: readonly [MasteryTrack, ...MasteryTrack[]],
  learn: readonly [string, string, string],
  lab: string,
  proof: string,
): Lesson {
  const youtubeId = youtubeIds[number];

  return {
    number,
    code: `EP ${pad(number)}`,
    slug: `${pad(number)}-${slugify(title)}`,
    title,
    phase: phaseFor(number),
    tracks,
    learn,
    lab,
    proof,
    prerequisites: number === 1 ? [] : [`EP ${pad(number - 1)}`],
    ...(youtubeId ? { youtubeId } : {}),
  };
}

